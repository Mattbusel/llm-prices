// Generates the price data of the Python package (python/src/llm_prices/_data.py), the npm
// package (js/src/data.ts) and the root ES module that `npm i github:Mattbusel/llm-prices` and
// the CDNs load (data.mjs with its types in data.d.mts) from prices.json, so none of them needs
// a JSON file at run time.
//
// Prices are written as the decimal text prices.json holds ("0.075", "15"), not as numbers:
// both packages parse that text into a float for the f64-style API and keep it for exact
// decimal costs, so a price is never re-printed by a language with different float formatting.

import { checkVersion } from './version.mjs';

// The exact decimal text of a price, as prices.json writes it (same rule as rust.mjs).
function dec(v) {
  const s = String(v);
  if (!/^\d+(\.\d+)?$/.test(s)) throw new Error(`price ${s} is not a plain decimal`);
  return s;
}

function text(v) {
  return v === null || v === undefined ? null : dec(v);
}

function cacheWrite(o) {
  const out = {};
  if (!o) return out;
  for (const [k, v] of Object.entries(o)) if (v !== null && v !== undefined) out[k] = dec(v);
  return out;
}

function tier(t) {
  return {
    input: text(t.input),
    output: text(t.output),
    cache_read: text(t.cache_read),
    cache_write: cacheWrite(t.cache_write),
    batch_input: text(t.batch_input),
    batch_output: text(t.batch_output),
  };
}

// The fields both packages carry: the Rust crate's `Price` plus `name` and `note`.
export function packageRows(doc) {
  return doc.models.map((m) => ({
    provider: m.provider,
    model: m.model,
    name: m.name ?? null,
    aliases: [...m.aliases],
    status: m.status,
    ...tier(m),
    long_context: m.long_context ? { threshold_tokens: m.long_context.threshold_tokens, ...tier(m.long_context) } : null,
    source_url: m.source_url,
    checked: m.checked,
    note: m.note ?? null,
  }));
}

// The Python rows also carry the other tiers (flex, priority, fast, offpeak, ...) with their
// own long-context prices, and the data residency multipliers.
function pythonRows(doc) {
  const base = packageRows(doc);
  return doc.models.map((m, i) => ({
    ...base[i],
    tiers: Object.fromEntries(
      Object.entries(m.other_tiers ?? {}).map(([name, t]) => [
        name,
        { ...tier(t), long_context: t.long_context ? { threshold_tokens: t.long_context.threshold_tokens, ...tier(t.long_context) } : null },
      ]),
    ),
    inference_geo: Object.fromEntries(Object.entries(m.inference_geo ?? {}).map(([k, v]) => [k, dec(v)])),
  }));
}

// A JS value as a Python literal. JSON string escapes are all valid Python escapes.
function py(v) {
  if (v === null || v === undefined) return 'None';
  if (v === true) return 'True';
  if (v === false) return 'False';
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'number') {
    if (!Number.isInteger(v)) throw new Error(`unexpected non-integer ${v}`);
    return String(v);
  }
  if (Array.isArray(v)) return v.length ? `(${v.map(py).join(', ')},)` : '()';
  return `{${Object.entries(v).map(([k, x]) => `${JSON.stringify(k)}: ${py(x)}`).join(', ')}}`;
}

export function toPython(doc, version) {
  checkVersion(version);
  const out = [
    '# @generated by scripts/build.mjs from prices.json. Do not edit by hand.',
    '"""The price table, generated from prices.json.',
    '',
    'Prices are the decimal text prices.json writes, USD per 1M tokens. ``None`` means the',
    "provider's page lists no price.",
    '"""',
    '',
    'from typing import Any, Dict, Tuple',
    '',
    '#: Date the table was generated (ISO 8601).',
    `GENERATED = ${py(doc.generated)}`,
    '',
    '#: SHA-256 of the prices.json this table was generated from (UTF-8, LF line endings).',
    `PRICES_VERSION = ${py(version)}`,
    '',
    'ROWS: Tuple[Dict[str, Any], ...] = (',
  ];
  for (const row of pythonRows(doc)) out.push(`    ${py(row)},`);
  out.push(')', '');
  return out.join('\n');
}

export function toTs(doc, version) {
  checkVersion(version);
  const out = [
    '// @generated by scripts/build.mjs from prices.json. Do not edit by hand.',
    '',
    '/** One price tier of a row as the decimal text prices.json writes, USD per 1M tokens. */',
    'export interface RawTier {',
    '  readonly input: string | null;',
    '  readonly output: string | null;',
    '  readonly cache_read: string | null;',
    '  readonly cache_write: Readonly<Record<string, string>>;',
    '  readonly batch_input: string | null;',
    '  readonly batch_output: string | null;',
    '}',
    '',
    '/** One row of prices.json, reduced to the fields the package uses. */',
    'export interface RawRow extends RawTier {',
    '  readonly provider: string;',
    '  readonly model: string;',
    '  readonly name: string | null;',
    '  readonly aliases: readonly string[];',
    '  readonly status: string;',
    '  readonly long_context: (RawTier & { readonly threshold_tokens: number }) | null;',
    '  readonly source_url: string;',
    '  readonly checked: string;',
    '  readonly note: string | null;',
    '}',
    '',
    '/** Date the table was generated (ISO 8601). */',
    `export const GENERATED = ${JSON.stringify(doc.generated)};`,
    '',
    '/** SHA-256 of the prices.json this table was generated from (UTF-8, LF line endings). */',
    `export const PRICES_VERSION = ${JSON.stringify(version)};`,
    '',
    'export const ROWS: readonly RawRow[] = [',
  ];
  for (const row of packageRows(doc)) out.push(`  ${JSON.stringify(row)},`);
  out.push('];', '');
  return out.join('\n');
}

const RAW_TYPES = [
  '/** One price tier of a row as the decimal text prices.json writes, USD per 1M tokens. */',
  'export interface RawTier {',
  '  readonly input: string | null;',
  '  readonly output: string | null;',
  '  readonly cache_read: string | null;',
  '  readonly cache_write: Readonly<Record<string, string>>;',
  '  readonly batch_input: string | null;',
  '  readonly batch_output: string | null;',
  '}',
  '',
  '/** One row of prices.json, reduced to the fields the package uses. */',
  'export interface RawRow extends RawTier {',
  '  readonly provider: string;',
  '  readonly model: string;',
  '  readonly name: string | null;',
  '  readonly aliases: readonly string[];',
  '  readonly status: string;',
  '  readonly long_context: (RawTier & { readonly threshold_tokens: number }) | null;',
  '  readonly source_url: string;',
  '  readonly checked: string;',
  '  readonly note: string | null;',
  '}',
];

/** data.mjs at the repository root: the rows of js/src/data.ts as plain JavaScript. */
export function toMjs(doc, version) {
  checkVersion(version);
  const out = [
    '// @generated by scripts/build.mjs from prices.json. Do not edit by hand.',
    '// The price table that index.mjs (the root ES module) reads; types are in data.d.mts.',
    '',
    '/** Date the table was generated (ISO 8601). */',
    `export const GENERATED = ${JSON.stringify(doc.generated)};`,
    '',
    '/** SHA-256 of the prices.json this table was generated from (UTF-8, LF line endings). */',
    `export const PRICES_VERSION = ${JSON.stringify(version)};`,
    '',
    'export const ROWS = [',
  ];
  for (const row of packageRows(doc)) out.push(`  ${JSON.stringify(row)},`);
  out.push('];', '');
  return out.join('\n');
}

/** data.d.mts at the repository root: the types of data.mjs. */
export function toMjsTypes() {
  return [
    '// @generated by scripts/build.mjs. Do not edit by hand.',
    '',
    ...RAW_TYPES,
    '',
    '/** Date the table was generated (ISO 8601). */',
    'export declare const GENERATED: string;',
    '',
    '/** SHA-256 of the prices.json this table was generated from (UTF-8, LF line endings). */',
    'export declare const PRICES_VERSION: string;',
    '',
    'export declare const ROWS: readonly RawRow[];',
    '',
  ].join('\n');
}
