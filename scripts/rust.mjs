// Generates crate/src/data.rs from prices.json so the crate needs no JSON parser.

import { checkVersion } from './version.mjs';

function f(v) {
  if (v === null || v === undefined) return 'None';
  const s = Number.isInteger(v) ? `${v}.0` : String(v);
  return `Some(${s})`;
}

function str(s) {
  return JSON.stringify(s ?? '');
}

function cw(o) {
  if (!o) return '&[]';
  const parts = Object.entries(o)
    .filter(([, v]) => v !== null && v !== undefined)
    .map(([k, v]) => `(${str(k)}, ${Number.isInteger(v) ? `${v}.0` : v})`);
  return `&[${parts.join(', ')}]`;
}

// The exact decimal text of a price, as prices.json writes it. JSON.stringify and Rust's f64
// Display both print the shortest text that round-trips, so this is the number on the page.
function dec(v) {
  const s = String(v);
  if (!/^\d+(\.\d+)?$/.test(s)) throw new Error(`price ${s} is not a plain decimal`);
  return s;
}

function sd(v) {
  return v === null || v === undefined ? 'None' : `Some(${str(dec(v))})`;
}

function cws(o) {
  if (!o) return '&[]';
  const parts = Object.entries(o)
    .filter(([, v]) => v !== null && v !== undefined)
    .map(([k, v]) => `(${str(k)}, ${str(dec(v))})`);
  return `&[${parts.join(', ')}]`;
}

function exactRates(r) {
  return `ExactRates { input: ${sd(r.input)}, output: ${sd(r.output)}, cache_read: ${sd(r.cache_read)}, cache_write: ${cws(r.cache_write)}, batch_input: ${sd(r.batch_input)}, batch_output: ${sd(r.batch_output)} }`;
}

export function toRust(doc, version) {
  checkVersion(version);
  const out = [
    '// @generated by scripts/update.mjs from prices.json. Do not edit by hand.',
    'use crate::{ExactRates, ExactRow, LongContext, Price};',
    '',
    `/// Date the table was generated (ISO 8601).`,
    `pub const GENERATED: &str = ${str(doc.generated)};`,
    '',
    '/// The SHA-256 of the prices.json this table was generated from (UTF-8, LF line endings), as',
    '/// `"sha256:<lowercase hex>"`. Every release states it in its notes; record it as',
    '/// `gen_ai.usage.cost.pricing.version` next to costs computed from this table.',
    `pub const PRICES_VERSION: &str = ${str(version)};`,
    '',
    'pub static PRICES: &[Price] = &[',
  ];
  for (const m of doc.models) {
    const lc = m.long_context
      ? `Some(LongContext { threshold_tokens: ${m.long_context.threshold_tokens}, input: ${f(m.long_context.input)}, output: ${f(m.long_context.output)}, cache_read: ${f(m.long_context.cache_read)}, cache_write: ${cw(m.long_context.cache_write)}, batch_input: ${f(m.long_context.batch_input)}, batch_output: ${f(m.long_context.batch_output)} })`
      : 'None';
    out.push(
      `    Price { provider: ${str(m.provider)}, model: ${str(m.model)}, aliases: &[${m.aliases.map(str).join(', ')}], status: ${str(m.status)}, input: ${f(m.input)}, output: ${f(m.output)}, cache_read: ${f(m.cache_read)}, cache_write: ${cw(m.cache_write)}, batch_input: ${f(m.batch_input)}, batch_output: ${f(m.batch_output)}, long_context: ${lc}, source_url: ${str(m.source_url)}, checked: ${str(m.checked)} },`,
    );
  }
  out.push(
    '];',
    '',
    '/// Other service tiers by row index in `PRICES`: (row, tier name, prices).',
    'pub(crate) static TIERS: &[(usize, &str, Price)] = &[',
  );
  doc.models.forEach((m, i) => {
    for (const [name, t] of Object.entries(m.other_tiers ?? {})) {
      const lc = t.long_context
        ? `Some(LongContext { threshold_tokens: ${t.long_context.threshold_tokens}, input: ${f(t.long_context.input)}, output: ${f(t.long_context.output)}, cache_read: ${f(t.long_context.cache_read)}, cache_write: ${cw(t.long_context.cache_write)}, batch_input: None, batch_output: None })`
        : 'None';
      out.push(
        `    (${i}, ${str(name)}, Price { provider: ${str(m.provider)}, model: ${str(m.model)}, aliases: &[${m.aliases.map(str).join(', ')}], status: ${str(m.status)}, input: ${f(t.input)}, output: ${f(t.output)}, cache_read: ${f(t.cache_read)}, cache_write: ${cw(t.cache_write)}, batch_input: None, batch_output: None, long_context: ${lc}, source_url: ${str(m.source_url)}, checked: ${str(m.checked)} }),`,
      );
    }
  });
  out.push(
    '];',
    '',
    '/// Data residency multipliers by row index in `PRICES`: (row, parameter value, multiplier text).',
    'pub(crate) static INFERENCE_GEO: &[(usize, &str, &str)] = &[',
  );
  doc.models.forEach((m, i) => {
    for (const [geo, v] of Object.entries(m.inference_geo ?? {})) out.push(`    (${i}, ${str(geo)}, ${str(dec(v))}),`);
  });
  out.push(
    '];',
    '',
    '/// The prices of each row of `PRICES`, in the same order, as the decimal text in prices.json.',
    'pub(crate) static EXACT: &[ExactRow] = &[',
  );
  for (const m of doc.models) {
    const lc = m.long_context ? `Some(${exactRates(m.long_context)})` : 'None';
    out.push(`    ExactRow { base: ${exactRates(m)}, long_context: ${lc} },`);
  }
  out.push('];', '');
  return out.join('\n');
}
