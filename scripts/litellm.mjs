// Generates litellm.json: the table in the schema of LiteLLM's
// model_prices_and_context_window.json (https://github.com/BerriAI/litellm), which LiteLLM,
// tokencost and many gateways read. Prices are USD per token there, so each one is the
// prices.json value divided by 1,000,000, computed on the decimal text (no float error).
//
// Keys follow LiteLLM's names: OpenAI and Anthropic ids are bare, other providers are
// prefixed ("gemini/gemini-2.5-pro", "deepseek/deepseek-flash", "fireworks_ai/..."). Tiers:
// batch -> *_batches, flex -> *_flex, priority and OpenAI's fast (OpenAI renamed Priority
// processing to Fast mode on 2026-07-30) -> *_priority; long context -> *_above_<N>k_tokens.
// Tiers LiteLLM has no keys for (Anthropic fast, DeepSeek offpeak, OpenAI ultrafast) and data
// residency multipliers are left out; prices.json has them.

const PROVIDER = {
  anthropic: ['anthropic', ''],
  openai: ['openai', ''],
  google: ['gemini', 'gemini/'],
  deepseek: ['deepseek', 'deepseek/'],
  mistral: ['mistral', 'mistral/'],
  xai: ['xai', 'xai/'],
  cohere: ['cohere_chat', ''],
  groq: ['groq', 'groq/'],
  together: ['together_ai', 'together_ai/'],
  fireworks: ['fireworks_ai', 'fireworks_ai/'],
};

// "2.5" USD per 1M -> 2.5e-6 USD per token, as the shortest float text of the exact quotient.
function perToken(v) {
  if (v === null || v === undefined) return undefined;
  const s = String(v);
  if (!/^\d+(\.\d+)?$/.test(s)) throw new Error(`price ${s} is not a plain decimal`);
  const [int, frac = ''] = s.split('.');
  const digits = (int + frac).replace(/^0+/, '') || '0';
  const exp = -(frac.length + 6);
  return Number(`${digits}e${exp}`);
}

function above(threshold) {
  const k = Math.round(threshold / 1000);
  return `_above_${k}k_tokens`;
}

function put(o, key, v) {
  const t = perToken(v);
  if (t !== undefined) o[key] = t;
}

// The price columns of one tier (base, a long-context tier, or an other tier).
function columns(o, t, suffix) {
  put(o, `input_cost_per_token${suffix}`, t.input);
  put(o, `output_cost_per_token${suffix}`, t.output);
  put(o, `cache_read_input_token_cost${suffix}`, t.cache_read);
  const cw = t.cache_write ?? {};
  // LiteLLM's cache_creation_input_token_cost is the default (5 minute) write; the 1 hour
  // write is cache_creation_input_token_cost_above_1hr.
  put(o, `cache_creation_input_token_cost${suffix}`, cw['5m']);
  if (cw['1h'] !== undefined && cw['1h'] !== null) {
    const t1 = perToken(cw['1h']);
    o[suffix ? `cache_creation_input_token_cost_above_1hr${suffix}` : 'cache_creation_input_token_cost_above_1hr'] = t1;
  }
}

function tierSuffix(provider, name) {
  if (name === 'flex') return '_flex';
  if (name === 'priority') return '_priority';
  if (provider === 'openai' && name === 'fast') return '_priority';
  return null;
}

export function toLitellm(doc) {
  const out = {};
  for (const m of doc.models) {
    if (m.input === null) continue;
    const [litellmProvider, prefix] = PROVIDER[m.provider] ?? [m.provider, `${m.provider}/`];
    const e = {};
    columns(e, m, '');
    put(e, 'input_cost_per_token_batches', m.batch_input);
    put(e, 'output_cost_per_token_batches', m.batch_output);
    if (m.long_context) {
      const lc = m.long_context;
      const sfx = above(lc.threshold_tokens);
      columns(e, lc, sfx);
      put(e, `input_cost_per_token${sfx}_batches`, lc.batch_input);
      put(e, `output_cost_per_token${sfx}_batches`, lc.batch_output);
    }
    for (const [name, t] of Object.entries(m.other_tiers ?? {})) {
      const sfx = tierSuffix(m.provider, name);
      if (!sfx) continue;
      columns(e, t, sfx);
      if (t.long_context) columns(e, t.long_context, `${above(t.long_context.threshold_tokens)}${sfx}`);
    }
    e.litellm_provider = litellmProvider;
    e.mode = m.output === null ? 'embedding' : 'chat';
    // Embedding models have no output tokens; LiteLLM's own rows write 0 there.
    if (e.mode === 'embedding' && e.output_cost_per_token === undefined) e.output_cost_per_token = 0;
    if (m.cache_read !== null || (m.cache_write && Object.keys(m.cache_write).length)) e.supports_prompt_caching = true;
    // Not LiteLLM fields; LiteLLM keeps unknown keys. They say where each price was read.
    e.source = m.source_url;
    e.llm_prices_checked = m.checked;
    for (const id of [m.model, ...m.aliases]) {
      const key = `${prefix}${id}`;
      if (!(key in out)) out[key] = e;
    }
  }
  const head = {
    sample_spec: {
      note: `Generated by llm-prices (https://github.com/Mattbusel/llm-prices) from prices.json, generated ${doc.generated}. USD per token. Every entry names the official pricing page it was read from in "source" and the date in "llm_prices_checked".`,
    },
  };
  return JSON.stringify({ ...head, ...out }, null, 2) + '\n';
}
